import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const entry = join(root, "index.html");
const output = join(root, "cv.pdf");
const generated = join(root, "src", "generated", "pdf.ts");

const chromium =
  process.env.CHROMIUM ??
  ["chromium", "chromium-browser", "google-chrome", "google-chrome-stable", "microsoft-edge"].find(
    (bin) => Bun.which(bin) !== null,
  );

if (!chromium) {
  throw new Error("No Chromium/Chrome binary found. Set CHROMIUM=/path/to/chromium.");
}

console.log(`[pdf] rendering ${entry} → ${output}`);

const proc = Bun.spawn(
  [
    chromium,
    "--headless=new",
    "--disable-gpu",
    "--hide-scrollbars",
    "--no-pdf-header-footer",
    "--virtual-time-budget=6000",
    `--print-to-pdf=${output}`,
    // pin both switches so a dark-mode desktop or a narrow headless window
    // can never change the generated document
    `${pathToFileURL(entry).href}?view=a4&theme=light`,
  ],
  { stdout: "inherit", stderr: "pipe" },
);

const code = await proc.exited;
if (code !== 0) {
  const err = await new Response(proc.stderr).text();
  throw new Error(`Chromium exited with ${code}\n${err}`);
}

if (!existsSync(output)) throw new Error("Chromium did not produce cv.pdf");

const pdf = await readFile(output);
const pages = pdf
  .toString("latin1")
  .match(/\/Type\s*\/Page[^s]/g)?.length ?? 0;

console.log(`[pdf] cv.pdf ${(pdf.byteLength / 1024).toFixed(1)} KiB · ${pages} page(s)`);

await mkdir(join(root, "src", "generated"), { recursive: true });
await writeFile(
  generated,
  `// generated by scripts/build-pdf.ts — do not edit\n` +
    `export const CV_PDF_BASE64 = ${JSON.stringify(pdf.toString("base64"))};\n`,
);

console.log(`[pdf] embedded ${pdf.byteLength} bytes into src/generated/pdf.ts`);
